#!/usr/bin/env python3
"""Generate src/features/bip39_wordlist.cpp and test vectors from the official files.

Usage: python3 tools/gen_bip39.py english.txt vectors.json
  english.txt  : https://github.com/bitcoin/bips/blob/master/bip-0039/english.txt
  vectors.json : https://github.com/trezor/python-mnemonic/blob/master/vectors.json
"""
import hashlib
import json
import pathlib
import sys

EXPECTED_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    raw = pathlib.Path(sys.argv[1]).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit(f"wordlist hash mismatch: {digest}")
    words = raw.decode().split()
    assert len(words) == 2048 and words == sorted(words)

    out = ["// Generated by tools/gen_bip39.py from the official BIP39 English wordlist.",
           f"// sha256(english.txt) = {EXPECTED_SHA256}",
           '#include "features/bip39.h"', "", "namespace cv {", "",
           "const char* const kBip39Words[2048] = {"]
    for i in range(0, 2048, 8):
        out.append("    " + " ".join(f'"{w}",' for w in words[i:i + 8]))
    out += ["};", "", "}  // namespace cv", ""]
    (ROOT / "src/features/bip39_wordlist.cpp").write_text("\n".join(out))

    vectors = json.loads(pathlib.Path(sys.argv[2]).read_text())["english"]
    vec = ["// Generated by tools/gen_bip39.py from trezor/python-mnemonic vectors.json.",
           "#pragma once", "", "struct Bip39Vector { const char* entropy_hex; const char* mnemonic; };",
           "", "static const Bip39Vector kBip39Vectors[] = {"]
    for entropy, mnemonic, *_ in vectors:
        vec.append(f'    {{"{entropy}", "{mnemonic}"}},')
    vec += ["};", ""]
    (ROOT / "test/test_features/bip39_vectors.h").write_text("\n".join(vec))
    print(f"ok: 2048 words, {len(vectors)} vectors")


if __name__ == "__main__":
    main()
